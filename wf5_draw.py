class Canvas:
    def __init__(self, w, h, bg=(255, 255, 255)):
        self.w = w
        self.h = h
        self.px = bytearray()
        for _ in range(w * h):
            self.px += bytes(bg)

    def set(self, x, y, c):
        if 0 <= x < self.w and 0 <= y < self.h:
            i = (y * self.w + x) * 3
            self.px[i] = c[0]
            self.px[i + 1] = c[1]
            self.px[i + 2] = c[2]

    def rect(self, x0, y0, x1, y1, c):
        for y in range(int(y0), int(y1)):
            for x in range(int(x0), int(x1)):
                self.set(x, y, c)

    def rect_outline(self, x0, y0, x1, y1, c, t=1):
        self.rect(x0, y0, x1, y0 + t, c)
        self.rect(x0, y1 - t, x1, y1, c)
        self.rect(x0, y0, x0 + t, y1, c)
        self.rect(x1 - t, y0, x1, y1, c)

    def line(self, x0, y0, x1, y1, c, t=1):
        x0, y0, x1, y1 = int(x0), int(y0), int(x1), int(y1)
        dx = abs(x1 - x0)
        dy = -abs(y1 - y0)
        sx = 1 if x0 < x1 else -1
        sy = 1 if y0 < y1 else -1
        err = dx + dy
        while True:
            for ox in range(-(t // 2), t // 2 + 1):
                for oy in range(-(t // 2), t // 2 + 1):
                    self.set(x0 + ox, y0 + oy, c)
            if x0 == x1 and y0 == y1:
                break
            e2 = 2 * err
            if e2 >= dy:
                err += dy
                x0 += sx
            if e2 <= dx:
                err += dx
                y0 += sy

    def circle(self, cx, cy, r, c, fill=True):
        for y in range(-r, r + 1):
            for x in range(-r, r + 1):
                if x * x + y * y <= r * r:
                    if fill or (x * x + y * y >= (r - 1) * (r - 1)):
                        self.set(cx + x, cy + y, c)

    def text(self, x, y, s, c=(0, 0, 0), scale=2, spacing=1):
        cx = x
        for ch in s:
            glyph = FONT.get(ch, FONT['?'] if ch not in FONT else FONT[ch])
            if ch == ' ':
                cx += (5 + spacing) * scale
                continue
            for ry, row in enumerate(glyph):
                for rx, bit in enumerate(row):
                    if bit == '1':
                        self.rect(cx + rx * scale, y + ry * scale,
                                  cx + rx * scale + scale, y + ry * scale + scale, c)
            cx += (5 + spacing) * scale
        return cx

    def text_w(self, s, scale=2, spacing=1):
        return len(s) * (5 + spacing) * scale

    def text_center(self, cx, y, s, c=(0, 0, 0), scale=2):
        w = self.text_w(s, scale)
        self.text(cx - w // 2, y, s, c, scale)

    def save(self, path):
        raw = bytearray()
        for y in range(self.h):
            raw.append(0)  # filter type 0
            start = y * self.w * 3
            raw += self.px[start:start + self.w * 3]
        compressed = zlib.compress(bytes(raw), 9)

        def chunk(typ, data):
            c = struct.pack('>I', len(data)) + typ + data
            crc = zlib.crc32(typ + data) & 0xffffffff
            return c + struct.pack('>I', crc)

        png = b'\x89PNG\r\n\x1a\n'
        ihdr = struct.pack('>IIBBBBB', self.w, self.h, 8, 2, 0, 0, 0)
        png += chunk(b'IHDR', ihdr)
        png += chunk(b'IDAT', compressed)
        png += chunk(b'IEND', b'')
        with open(path, 'wb') as f:
            f.write(png)
