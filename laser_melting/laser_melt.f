      ENTRY GAMSOR
      IF(NF.EQ.1) THEN
         DO 700 J=1,M1
            DO 700 I=1,L1
               GAM(I,J)=AMU
  700    CONTINUE
         DO 701 J=2,M2
            DO 701 I=IST,L2
               EPS=0.5D0*(FACT1(I,J)+FACT1(I-1,J))
               VOL=YCVR(J)*XCVS(I)
               DARCY=-CMUSH*(1.0D0-EPS)**2/(EPS**3+B)
               AP(I,J)=AP(I,J)+DARCY*VOL
               TP2=0.5D0*(T(I,J)+T(I-1,J))
               CON(I,J)=CON(I,J)+DENREF*GRAV*BETA*(TP2-TREF)*VOL
  701    CONTINUE
      ELSE IF(NF.EQ.2) THEN
         DO 710 J=1,M1
            DO 710 I=1,L1
               GAM(I,J)=AMU
  710    CONTINUE
         DO 711 J=JST,M2
            DO 711 I=2,L2
               EPS=0.5D0*(FACT1(I,J)+FACT1(I,J-1))
               VOL=RMN(J)*YCVS(J)*XCV(I)
               DARCY=-CMUSH*(1.0D0-EPS)**2/(EPS**3+B)
               AP(I,J)=AP(I,J)+DARCY*VOL
               IF(MODE.EQ.2) THEN
                  GAMP=0.5D0*(GAM(I,J)+GAM(I,J-1))
                  AP2=-GAMP/(RMN(J)*RMN(J))
                  AP(I,J)=AP(I,J)+AP2*VOL
               END IF
  711    CONTINUE
      ELSE IF(NF.EQ.5) THEN
         DO 720 J=1,M1
            DO 720 I=1,L1
               COND=FACT1(I,J)*CONDL+(1.0D0-FACT1(I,J))*CONDS
               GAM(I,J)=COND
  720    CONTINUE
         DO 721 I=1,L1
            GAM(I,1)=0.0D0
            GAM(I,M1)=0.0D0
  721    CONTINUE
         DO 722 J=1,M1
            GAM(1,J)=0.0D0
            GAM(L1,J)=0.0D0
  722    CONTINUE
         IF(TIME.LE.TR) THEN
            FT=TIME/TR
         ELSE IF(TIME.LE.(TP-TF)) THEN
            FT=1.0D0
         ELSE IF(TIME.LE.TP) THEN
            FT=(TP-TIME)/TF
         ELSE
            FT=0.0D0
         END IF
         DO 723 J=2,M2
            RR=Y(J)
            SURFLUX=PKINTENSITY*FT*DEXP(-2.0D0*RR*RR/ASQUARE)
            REFLEC=FACT1(2,J)*REFLECL+(1.0D0-FACT1(2,J))*REFLECS
            ABSFLUX=(1.0D0-REFLEC)*SURFLUX
            DO 724 I=2,L2
               DEPTH=X(I)-X(2)
               ENTSRCPERVOL=ABSFLUX*ABSORCOF*DEXP(-ABSORCOF*DEPTH)
               VOL=YCVR(J)*XCV(I)
               CON(I,J)=CON(I,J)+ENTSRCPERVOL*VOL
  724       CONTINUE
  723    CONTINUE
         DO 725 J=2,M2
            DO 725 I=2,L2
               CONVT=RHO(I,J,5)*U(I,J)*HIF*FACT1(I,J)
               CON(I,J)=CON(I,J)-CONVT*YCVR(J)
  725    CONTINUE
         DO 726 J=2,M2
            COND=FACT1(2,J)*CONDL+(1.0D0-FACT1(2,J))*CONDS
            RADRES=SIGMA*(T(2,J)+T(1,J))*(T(2,J)*T(2,J)+T(1,J)*T(1,J))
            HEFF=HTC+RADRES
            AREA=YCVR(J)
            CONEXTRA=HEFF*TINIT*AREA
            APEXTRA=-HEFF*AREA
            CON(2,J)=CON(2,J)+CONEXTRA
            AP(2,J)=AP(2,J)+APEXTRA
  726    CONTINUE
      END IF
      RETURN
C-----------------------------------------------------------------
      ENTRY LC
      DO 800 J=2,M2
         DO 800 I=2,L2
            APSUM(I,J)=AP(I,J)
  800 CONTINUE
      RETURN
      END
