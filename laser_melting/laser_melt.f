               TEMP=CON(I,J)+AJP(I,J)*F(I,J+1,NF)+AJM(I,J)*F(I,J-1,NF)
               QT(I)=(TEMP+AIM(I,J)*QT(I-1))/DENOM
   51       CONTINUE
            DO 52 II=2,L2
               I=L2+2-II
               F(I,J,NF)=F(I+1,J,NF)*PT(I)+QT(I)
   52       CONTINUE
   50    CONTINUE
  999 CONTINUE
      RETURN
C-----------------------------------------------------------------
      ENTRY RESET
      DO 900 J=2,M2
         DO 900 I=2,L2
            CON(I,J)=0.0D0
            AP(I,J)=0.0D0
  900 CONTINUE
      RETURN
