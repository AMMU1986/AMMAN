         END IF
      END IF
      IF(KSOLVE(1).EQ.1 .OR. KSOLVE(2).EQ.1) THEN
         SMAX=0.0D0
         SSUM=0.0D0
         DO 630 J=2,M2
            DO 630 I=2,L2
