            VC=0.5D0*(V(I,J)+V(I,MIN(J+1,M1)))
            WRITE(30,30) X(I),Y(J),UC,VC,F(I,J,5),FACT1(I,J)
   30       FORMAT(1P,6E14.5)
  100 CONTINUE
      RETURN
      END
      SUBROUTINE GETIME(INDX)
      IMPLICIT DOUBLE PRECISION (A-H, O-Z)
      INTEGER IV(8)
      INTEGER IYS,IMS,IDS,IHS,IMINS,ISECS
      SAVE IYS,IMS,IDS,IHS,IMINS,ISECS
   10 FORMAT(1X,'PROGRAM STARTED ON ',I2.2,'/',I2.2,'/',I4.4,
     1       ' AT ',I2.2,':',I2.2,':',I2.2)
   20 FORMAT(1X,'PROGRAM ENDED ON ',I2.2,'/',I2.2,'/',I4.4,
     1       ' AT ',I2.2,':',I2.2,':',I2.2)
   30 FORMAT(1X,'TOTAL RUN TIME =',1P,E14.5,' SECONDS')
      CALL DATE_AND_TIME(VALUES=IV)
      IF(INDX.EQ.1) THEN
         IYS=IV(1)
         IMS=IV(2)
         IDS=IV(3)
         IHS=IV(5)
         IMINS=IV(6)
         ISECS=IV(7)
      ELSE
         IYE=IV(1)
         IME=IV(2)
         IDE=IV(3)
         IHE=IV(5)
         IMINE=IV(6)
         ISECE=IV(7)
         WRITE(6,10) IDS,IMS,IYS,IHS,IMINS,ISECS
         WRITE(7,10) IDS,IMS,IYS,IHS,IMINS,ISECS
         WRITE(6,20) IDE,IME,IYE,IHE,IMINE,ISECE
         WRITE(7,20) IDE,IME,IYE,IHE,IMINE,ISECE
         SECS=DFLOAT(IHS)*3600.0D0+DFLOAT(IMINS)*60.0D0+DFLOAT(ISECS)
         SECE=DFLOAT(IHE)*3600.0D0+DFLOAT(IMINE)*60.0D0+DFLOAT(ISECE)
         TOTAL=SECE-SECS
         IF(IDE.NE.IDS) TOTAL=TOTAL+DFLOAT(IDE-IDS)*86400.0D0
         WRITE(6,30) TOTAL
         WRITE(7,30) TOTAL
      END IF
      RETURN
      END
