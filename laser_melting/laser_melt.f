     3 NTIMES(NFMAX),NSTPS,ISTEP,NREPT,ITER,KOP,ISOLID(NI,NJ)
      COMMON/BLK08/NCVLX,NCVLY,NCVX(NZMAX),NCVY(NZMAX),NZX,NZY
      COMMON/BLK09/POWERX,POWERY,XZONE(NZMAX),POWRX(NZMAX),
     1    YZONE(NZMAX),POWRY(NZMAX)
      COMMON/BLK10/SMAX,SSUM,BIG,SMALL
      COMMON/BLK11/TIME,DT,PI,HIF
      COMMON/BLK12/TITLE(NFMAX)
      COMMON/BLK13/RELAX(NFMAX),XL,YL,RHOCON
      COMMON/BLK14/IU1,IU2,ITPRNT,ITSTRT
      COMMON/BLK15/SAVEF,STARTF,PRINTF
      COMMON/BLK16/VIS(NI,NJ),SHEAR(NI,NJ),RELSOR
C
      DIMENSION U(NI,NJ),V(NI,NJ),PC(NI,NJ),P(NI,NJ)
      EQUIVALENCE(F(1,1,1),U(1,1)),(F(1,1,2),V(1,1)),(F(1,1,3),PC(1,1))
     1    ,(F(1,1,4),P(1,1))
      DIMENSION UOLD(NI,NJ),VOLD(NI,NJ)
      EQUIVALENCE(FOLD(1,1,1),UOLD(1,1)),(FOLD(1,1,2),VOLD(1,1))
      DIMENSION COF(NI,NJ,6),COFU(NI,NJ,6),COFV(NI,NJ,6),COFP(NI,NJ,6)
      EQUIVALENCE(COF(1,1,1),CON(1,1))
      DIMENSION TH(NI),THU(NI),THDIF(NI),THCV(NI),THCVS(NI)
      EQUIVALENCE(X,TH),(XU,THU),(XDIF,THDIF),(XCV,THCV)
     1  ,(XCVS,THCVS),(XL,THL)
      DIMENSION UHAT(NI,NJ),VHAT(NI,NJ)
    1 FORMAT(1X,'CARTESIAN COORDINATE SYSTEM')
    2 FORMAT(1X,'AXISYMMETRIC COORDINATE SYSTEM')
    3 FORMAT(1X,'POLAR COORDINATE SYSTEM')
    4 FORMAT(1X,'MODE =',I3)
C-----------------------------------------------------------------
      ENTRY DEFLT
      PRINTF='print.dat'
      NP=4
      PI=3.14159265358979D0
      IU1=6
      IU2=7
      XL=1.0D0
      YL=1.0D0
      NCVLX=5
      NCVLY=5
      DO 1101 N=1,NZMAX
         XZONE(N)=0.0D0
         YZONE(N)=0.0D0
         POWRX(N)=1.0D0
         POWRY(N)=1.0D0
         NCVX(N)=1
         NCVY(N)=1
 1101 CONTINUE
      SMALL=1.0D-17
      BIG=1.0D17
      MODE=1
      LAST=10
      TIME=0.0D0
      DT=BIG
      IPREF=1
      JPREF=1
      RHOCON=1.0D0
      KSTOP=0
      DO 1100 N=1,NFMAX
         KSOLVE(N)=0
         KPRINT(N)=0
         KBLK(N)=0
         RELAX(N)=1.0D0
         NTIMES(N)=10
 1100 CONTINUE
      DO 1102 N=1,NFMAX
         DO 1102 J=1,NJ
            DO 1102 I=1,NI
               F(I,J,N)=0.0D0
 1102 CONTINUE
      DO 1103 N=1,NFMAX
         DO 1103 J=1,NJ
            DO 1103 I=1,NI
               FOLD(I,J,N)=0.0D0
 1103 CONTINUE
      DO 1104 J=1,NJ
         DO 1104 I=1,NI
            ISOLID(I,J)=0
 1104 CONTINUE
      RETURN
C-----------------------------------------------------------------
      ENTRY SETUP1
      L2=L1-1
      L3=L2-1
      M2=M1-1
      M3=M2-1
      X(1)=XU(2)
      DO 11 I=2,L2
         X(I)=0.5D0*(XU(I+1)+XU(I))
   11 CONTINUE
      X(L1)=XU(L1)
      DO 12 I=2,L1
         XDIF(I)=X(I)-X(I-1)
   12 CONTINUE
      DO 13 I=2,L2
         XCV(I)=XU(I+1)-XU(I)
   13 CONTINUE
      DO 14 I=3,L2
         XCVS(I)=XDIF(I)
   14 CONTINUE
      XCVS(3)=XCVS(3)+XDIF(2)
      XCVS(L2)=XCVS(L2)+XDIF(L1)
      DO 15 I=3,L3
         XCVI(I)=0.5D0*XCV(I)
         XCVIP(I)=XCVI(I)
   15 CONTINUE
      XCVIP(2)=XCV(2)
      XCVI(L2)=XCV(L2)
      Y(1)=YV(2)
      DO 16 J=2,M2
         Y(J)=0.5D0*(YV(J+1)+YV(J))
   16 CONTINUE
      Y(M1)=YV(M1)
      DO 17 J=2,M1
         YDIF(J)=Y(J)-Y(J-1)
   17 CONTINUE
      DO 18 J=2,M2
         YCV(J)=YV(J+1)-YV(J)
   18 CONTINUE
      DO 19 J=3,M2
         YCVS(J)=YDIF(J)
   19 CONTINUE
      YCVS(3)=YCVS(3)+YDIF(2)
      YCVS(M2)=YCVS(M2)+YDIF(M1)
      IF(MODE.NE.1) GO TO 24
      DO 20 J=1,M1
         RMN(J)=1.0D0
         R(J)=1.0D0
   20 CONTINUE
      GO TO 26
   24 CONTINUE
      DO 22 J=2,M1
         R(J)=R(J-1)+YDIF(J)
   22 CONTINUE
      RMN(2)=R(1)
      DO 23 J=3,M2
         RMN(J)=RMN(J-1)+YCV(J-1)
   23 CONTINUE
      RMN(M1)=R(M1)
   26 CONTINUE
      DO 27 J=1,M1
         SX(J)=1.0D0
         SXMN(J)=1.0D0
         IF(MODE.NE.3) GO TO 27
         SX(J)=R(J)
         IF(J.NE.1) SXMN(J)=RMN(J)
   27 CONTINUE
      DO 28 J=2,M2
         YCVR(J)=R(J)*YCV(J)
         ARX(J)=YCVR(J)
         IF(MODE.NE.3) GO TO 28
         ARX(J)=YCV(J)
   28 CONTINUE
      DO 29 J=4,M3
         YCVRS(J)=0.5D0*(R(J)+R(J-1))*YDIF(J)
   29 CONTINUE
      YCVRS(3)=0.5D0*(R(3)+R(1))*YCVS(3)
      YCVRS(M2)=0.5D0*(R(M1)+R(M3))*YCVS(M2)
      IF(MODE.NE.2) GO TO 34
      DO 30 J=3,M3
         ARXJ(J)=0.25D0*(1.0D0+RMN(J)/R(J))*ARX(J)
         ARXJP(J)=ARX(J)-ARXJ(J)
   30 CONTINUE
      GO TO 37
   34 CONTINUE
      DO 35 J=3,M3
         ARXJ(J)=0.5D0*ARX(J)
         ARXJP(J)=ARXJ(J)
   35 CONTINUE
   37 CONTINUE
      ARXJP(2)=ARX(2)
      ARXJ(M2)=ARX(M2)
      DO 40 J=3,M3
         FV(J)=ARXJP(J)/ARX(J)
         FVP(J)=1.0D0-FV(J)
   40 CONTINUE
      DO 41 I=3,L2
         FX(I)=0.5D0*XCV(I-1)/XDIF(I)
         FXM(I)=1.0D0-FX(I)
   41 CONTINUE
      FX(2)=0.0D0
      FXM(2)=1.0D0
      FX(L1)=1.0D0
      FXM(L1)=0.0D0
      DO 42 J=3,M2
         FY(J)=0.5D0*YCV(J-1)/YDIF(J)
         FYM(J)=1.0D0-FY(J)
   42 CONTINUE
      FY(2)=0.0D0
      FYM(2)=1.0D0
      FY(M1)=1.0D0
      FYM(M1)=0.0D0
      DO 50 J=1,M1
         DO 50 I=1,L1
            CON(I,J)=0.0D0
            AP(I,J)=0.0D0
            U(I,J)=0.0D0
            V(I,J)=0.0D0
            PC(I,J)=0.0D0
            P(I,J)=0.0D0
            RHO(I,J,NFMAX)=RHOCON
            RHOLD(I,J,NFMAX)=RHOCON
   50 CONTINUE
      WRITE(6,4) MODE
      WRITE(7,4) MODE
      IF(MODE.EQ.1) WRITE(6,1)
      IF(MODE.EQ.2) WRITE(6,2)
      IF(MODE.EQ.3) WRITE(6,3)
      IF(MODE.EQ.1) WRITE(7,1)
      IF(MODE.EQ.2) WRITE(7,2)
      IF(MODE.EQ.3) WRITE(7,3)
      RETURN
C-----------------------------------------------------------------
      ENTRY SETUP2
C.... U MOMENTUM
      NF=1
      IST=3
      JST=2
      CALL DENSE
      CALL GAMSOR
      DO 100 J=2,M2
         DO 100 I=IST,L2
            AREA=YCVR(J)
            FLOW=AREA*U(I,J)*0.5D0*(RHO(I,J,NFMAX)+RHO(I-1,J,NFMAX))
            DIFF=AREA*GAM(I,J)/XCV(I-1)
            CALL DIFLOW(FLOW,DIFF,ACOF)
            AIM(I,J)=ACOF+DMAX1(0.0D0,FLOW)
  100 CONTINUE
      DO 101 J=2,M2
         DO 101 I=IST,L2
            AREA=YCVR(J)
            FLOW=AREA*U(I+1,J)*0.5D0*(RHO(I,J,NFMAX)+RHO(I+1,J,NFMAX))
            DIFF=AREA*GAM(I,J)/XCV(I)
            CALL DIFLOW(FLOW,DIFF,ACOF)
            AIP(I,J)=ACOF+DMAX1(0.0D0,-FLOW)
  101 CONTINUE
      DO 102 J=2,M2
         DO 102 I=IST,L2
            AREA=SX(J)*XCVS(I)
            FLOW=AREA*V(I,J)*0.5D0*(RHO(I,J,NFMAX)+RHO(I-1,J,NFMAX))
            DIFF=AREA*0.5D0*(GAM(I,J)+GAM(I-1,J))/YDIF(J)
            CALL DIFLOW(FLOW,DIFF,ACOF)
            AJM(I,J)=ACOF+DMAX1(0.0D0,FLOW)
  102 CONTINUE
      DO 103 J=2,M2
         DO 103 I=IST,L2
            AREA=SXMN(J+1)*XCVS(I)
            FLOW=AREA*V(I,J+1)*0.5D0*(RHO(I,J,NFMAX)+RHO(I-1,J,NFMAX))
            DIFF=AREA*0.5D0*(GAM(I,J)+GAM(I-1,J))/YDIF(J+1)
            CALL DIFLOW(FLOW,DIFF,ACOF)
            AJP(I,J)=ACOF+DMAX1(0.0D0,-FLOW)
  103 CONTINUE
      DO 104 J=2,M2
         DO 104 I=IST,L2
            VOL=YCVR(J)*XCVS(I)
            APT=0.5D0*(RHOLD(I,J,NFMAX)+RHOLD(I-1,J,NFMAX))*VOL/DT
            AP(I,J)=AP(I,J)-APT
            CON(I,J)=CON(I,J)+APT*UOLD(I,J)
            AP(I,J)=(-AP(I,J)+AIP(I,J)+AIM(I,J)+AJP(I,J)+AJM(I,J))
     1              /RELAX(NF)
            CON(I,J)=CON(I,J)+(1.0D0-RELAX(NF))*AP(I,J)*U(I,J)
            DU(I,J)=AREA/AP(I,J)
            COFU(I,J,1)=AIP(I,J)
            COFU(I,J,2)=AIM(I,J)
            COFU(I,J,3)=AJP(I,J)
            COFU(I,J,4)=AJM(I,J)
            COFU(I,J,5)=AP(I,J)
            COFU(I,J,6)=CON(I,J)
  104 CONTINUE
      DO 105 J=2,M2
         DO 105 I=IST,L2
            AREA=YCVR(J)
            DU(I,J)=AREA/AP(I,J)
  105 CONTINUE
C.... V MOMENTUM
      NF=2
      CALL RESET
      IST=2
      JST=3
      CALL DENSE
      CALL GAMSOR
      DO 110 J=JST,M2
         DO 110 I=2,L2
            AREA=RMN(J)*XCV(I)
            FLOW=AREA*V(I,J)*0.5D0*(RHO(I,J,NFMAX)+RHO(I,J-1,NFMAX))
            DIFF=AREA*0.5D0*(GAM(I,J)+GAM(I,J-1))/YCV(J-1)
            CALL DIFLOW(FLOW,DIFF,ACOF)
            AJM(I,J)=ACOF+DMAX1(0.0D0,FLOW)
  110 CONTINUE
      DO 111 J=JST,M2
         DO 111 I=2,L2
            AREA=R(J)*XCV(I)
            FLOW=AREA*V(I,J+1)*0.5D0*(RHO(I,J,NFMAX)+RHO(I,J+1,NFMAX))
            DIFF=AREA*0.5D0*(GAM(I,J)+GAM(I,J+1))/YCV(J)
            CALL DIFLOW(FLOW,DIFF,ACOF)
            AJP(I,J)=ACOF+DMAX1(0.0D0,-FLOW)
  111 CONTINUE
      DO 112 J=JST,M2
         DO 112 I=2,L2
            AREA=RMN(J)*YCVS(J)
            FLOW=AREA*U(I,J)*0.5D0*(RHO(I,J,NFMAX)+RHO(I,J-1,NFMAX))
            DIFF=AREA*0.5D0*(GAM(I,J)+GAM(I,J-1))/XDIF(I)
            CALL DIFLOW(FLOW,DIFF,ACOF)
            AIM(I,J)=ACOF+DMAX1(0.0D0,FLOW)
  112 CONTINUE
      DO 113 J=JST,M2
         DO 113 I=2,L2
            AREA=RMN(J)*YCVS(J)
            FLOW=AREA*U(I+1,J)*0.5D0*(RHO(I,J,NFMAX)+RHO(I,J-1,NFMAX))
            DIFF=AREA*0.5D0*(GAM(I,J)+GAM(I,J-1))/XDIF(I+1)
            CALL DIFLOW(FLOW,DIFF,ACOF)
            AIP(I,J)=ACOF+DMAX1(0.0D0,-FLOW)
  113 CONTINUE
      DO 114 J=JST,M2
         DO 114 I=2,L2
            VOL=RMN(J)*YCVS(J)*XCV(I)
            APT=0.5D0*(RHOLD(I,J,NFMAX)+RHOLD(I,J-1,NFMAX))*VOL/DT
            AP(I,J)=AP(I,J)-APT
            CON(I,J)=CON(I,J)+APT*VOLD(I,J)
            AREA=RMN(J)*XCV(I)
            AP(I,J)=(-AP(I,J)+AIP(I,J)+AIM(I,J)+AJP(I,J)+AJM(I,J))
     1              /RELAX(NF)
            CON(I,J)=CON(I,J)+(1.0D0-RELAX(NF))*AP(I,J)*V(I,J)
            DV(I,J)=AREA/AP(I,J)
            COFV(I,J,1)=AIP(I,J)
            COFV(I,J,2)=AIM(I,J)
            COFV(I,J,3)=AJP(I,J)
            COFV(I,J,4)=AJM(I,J)
            COFV(I,J,5)=AP(I,J)
            COFV(I,J,6)=CON(I,J)
  114 CONTINUE
C.... UHAT, VHAT
      DO 120 J=2,M2
         DO 120 I=3,L2
            UHAT(I,J)=(COFU(I,J,1)*U(I+1,J)+COFU(I,J,2)*U(I-1,J)
     1               +COFU(I,J,3)*U(I,J+1)+COFU(I,J,4)*U(I,J-1)
     2               +COFU(I,J,6))/COFU(I,J,5)
  120 CONTINUE
      DO 121 J=3,M2
         DO 121 I=2,L2
            VHAT(I,J)=(COFV(I,J,1)*V(I+1,J)+COFV(I,J,2)*V(I-1,J)
     1               +COFV(I,J,3)*V(I,J+1)+COFV(I,J,4)*V(I,J-1)
     2               +COFV(I,J,6))/COFV(I,J,5)
  121 CONTINUE
C.... PRESSURE CORRECTION
      NF=3
      CALL RESET
      DO 130 J=2,M2
         DO 130 I=2,L2
            AREA=YCVR(J)
            IF(I.EQ.2) THEN
               AIM(I,J)=0.0D0
            ELSE
               AIM(I,J)=AREA*0.5D0*(RHO(I,J,NFMAX)+RHO(I-1,J,NFMAX))
     1                  *DU(I,J)
            END IF
            IF(I.EQ.L2) THEN
               AIP(I,J)=0.0D0
            ELSE
               AIP(I,J)=AREA*0.5D0*(RHO(I,J,NFMAX)+RHO(I+1,J,NFMAX))
     1                  *DU(I+1,J)
            END IF
  130 CONTINUE
      DO 131 J=2,M2
         DO 131 I=2,L2
            AREA=RMN(J)*XCV(I)
            IF(J.EQ.2) THEN
               AJM(I,J)=0.0D0
            ELSE
               AJM(I,J)=AREA*0.5D0*(RHO(I,J,NFMAX)+RHO(I,J-1,NFMAX))
     1                  *DV(I,J)
            END IF
            AREA=R(J)*XCV(I)
            IF(J.EQ.M2) THEN
               AJP(I,J)=0.0D0
            ELSE
               AJP(I,J)=AREA*0.5D0*(RHO(I,J,NFMAX)+RHO(I,J+1,NFMAX))
     1                  *DV(I,J+1)
            END IF
  131 CONTINUE
      DO 132 J=2,M2
         DO 132 I=2,L2
            AREAX=YCVR(J)
            AREAY=RMN(J)*XCV(I)
            AREAYP=R(J)*XCV(I)
            AMS=0.5D0*(RHO(I,J,NFMAX)+RHO(I-1,J,NFMAX))*UHAT(I,J)*AREAX
     1        -0.5D0*(RHO(I,J,NFMAX)+RHO(I+1,J,NFMAX))*UHAT(I+1,J)*AREAX
     2        +0.5D0*(RHO(I,J,NFMAX)+RHO(I,J-1,NFMAX))*VHAT(I,J)*AREAY
     3        -0.5D0*(RHO(I,J,NFMAX)+RHO(I,J+1,NFMAX))*VHAT(I,J+1)*AREAYP
            CON(I,J)=AMS
            AP(I,J)=AIP(I,J)+AIM(I,J)+AJP(I,J)+AJM(I,J)
            PC(I,J)=0.0D0
  132 CONTINUE
      CALL SOLVE
C.... VELOCITY CORRECTION
      DO 140 J=2,M2
         DO 140 I=3,L2
            U(I,J)=UHAT(I,J)+DU(I,J)*(PC(I-1,J)-PC(I,J))
  140 CONTINUE
      DO 141 J=3,M2
         DO 141 I=2,L2
            V(I,J)=VHAT(I,J)+DV(I,J)*(PC(I,J-1)-PC(I,J))
  141 CONTINUE
      DO 142 J=2,M2
         DO 142 I=2,L2
            P(I,J)=P(I,J)+PC(I,J)
  142 CONTINUE
C.... SCALAR/TEMPERATURE EQUATIONS
      DO 200 N=5,NFMAX
         IF(KSOLVE(N).EQ.0) GO TO 200
         NF=N
         CALL RESET
         IST=2
         JST=2
         CALL DENSE
         CALL GAMSOR
         DO 210 J=2,M2
            DO 210 I=2,L2
               AREA=YCVR(J)
               FLOW=AREA*U(I,J)*RHO(I-1,J,NFMAX)
               DIFF=AREA*GAM(I-1,J)/XDIF(I)
               CALL DIFLOW(FLOW,DIFF,ACOF)
               AIM(I,J)=ACOF+DMAX1(0.0D0,FLOW)
  210    CONTINUE
         DO 211 J=2,M2
            DO 211 I=2,L2
               AREA=YCVR(J)
               FLOW=AREA*U(I+1,J)*RHO(I+1,J,NFMAX)
               DIFF=AREA*GAM(I+1,J)/XDIF(I+1)
               CALL DIFLOW(FLOW,DIFF,ACOF)
               AIP(I,J)=ACOF+DMAX1(0.0D0,-FLOW)
  211    CONTINUE
         DO 212 J=2,M2
            DO 212 I=2,L2
               AREA=RMN(J)*XCV(I)
               FLOW=AREA*V(I,J)*RHO(I,J-1,NFMAX)
               DIFF=AREA*GAM(I,J-1)/YDIF(J)
               CALL DIFLOW(FLOW,DIFF,ACOF)
               AJM(I,J)=ACOF+DMAX1(0.0D0,FLOW)
  212    CONTINUE
         DO 213 J=2,M2
            DO 213 I=2,L2
               AREA=R(J)*XCV(I)
               FLOW=AREA*V(I,J+1)*RHO(I,J+1,NFMAX)
               DIFF=AREA*GAM(I,J+1)/YDIF(J+1)
               CALL DIFLOW(FLOW,DIFF,ACOF)
               AJP(I,J)=ACOF+DMAX1(0.0D0,-FLOW)
  213    CONTINUE
         DO 214 J=2,M2
            DO 214 I=2,L2
               VOL=YCVR(J)*XCV(I)
               APT=RHOLD(I,J,NFMAX)*VOL/DT
               APTNEW=RHO(I,J,NFMAX)*VOL/DT
               AP(I,J)=AP(I,J)-APT
               CON(I,J)=CON(I,J)+APT*FOLD(I,J,N)
               AP(I,J)=(-AP(I,J)+AIP(I,J)+AIM(I,J)+AJP(I,J)+AJM(I,J)
     1                 +APTNEW-APT)/RELAX(NF)
               CON(I,J)=CON(I,J)+(1.0D0-RELAX(NF))*AP(I,J)*F(I,J,N)
  214    CONTINUE
         CALL LC
         CALL SOLVE
  200 CONTINUE
      RETURN
      END
