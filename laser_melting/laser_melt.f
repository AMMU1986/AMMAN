      SUBROUTINE DIFLOW(FLOW,DIFF,ACOF)
      IMPLICIT DOUBLE PRECISION (A-H, O-Z)
      ACOF=DIFF
      IF(FLOW.EQ.0.0D0) RETURN
      TEMP=DIFF-ABS(FLOW)*0.1D0
      ACOF=0.0D0
      IF(TEMP.LE.0.0D0) RETURN
      TEMP=TEMP/DIFF
      ACOF=DIFF*TEMP*TEMP*TEMP*TEMP*TEMP
      RETURN
      END
