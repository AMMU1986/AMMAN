     3 Y(NJ),YV(NJ),YDIF(NJ),YCV(NJ),YCVS(NJ),
     4 YCVR(NJ),YCVRS(NJ),ARX(NJ),ARXJ(NJ),ARXJP(NJ),
     5 R(NJ),RMN(NJ),SX(NJ),SXMN(NJ),XCVI(NI),XCVIP(NI)
      COMMON/BLK06/DU(NI,NJ),DV(NI,NJ),FV(NJ),FVP(NJ),
     1 FX(NI),FXM(NI),FY(NJ),FYM(NJ),PT(NIJ),QT(NIJ)
      COMMON/BLK07/NF,NP,NRHO,NGAM,L1,L2,L3,M1,M2,M3,
     1 IST,JST,LAST,KSTOP,IPREF,JPREF,KSOLVE(NFMAX),KPRINT(NFMAX),
     2 KBLK(NFMAX),MODE,
     3 NTIMES(NFMAX),NSTPS,ISTEP,NREPT,ITER,KOP,ISOLID(NI,NJ)
      COMMON/BLK08/NCVLX,NCVLY,NCVX(NZMAX),NCVY(NZMAX),NZX,NZY
      COMMON/BLK09/POWERX,POWERY,XZONE(NZMAX),POWRX(NZMAX),
     1    YZONE(NZMAX),POWRY(NZMAX)
