class Canvas:
    def __init__(self, w, h, bg=(255, 255, 255)):
        self.w = w
        self.h = h
        self.px = bytearray([bg[0], bg[1], bg[2]] * (w * h))

    def _set(self, x, y, c):
        if 0 <= x < self.w and 0 <= y < self.h:
            i = (y * self.w + x) * 3
            self.px[i] = c[0]
            self.px[i + 1] = c[1]
            self.px[i + 2] = c[2]

    def _blend(self, x, y, c, a):
        if 0 <= x < self.w and 0 <= y < self.h and a > 0:
            i = (y * self.w + x) * 3
            ia = 1 - a
            self.px[i] = int(self.px[i] * ia + c[0] * a)
            self.px[i + 1] = int(self.px[i + 1] * ia + c[1] * a)
            self.px[i + 2] = int(self.px[i + 2] * ia + c[2] * a)

    def rect(self, x0, y0, x1, y1, c):
        x0, x1 = sorted((int(x0), int(x1)))
        y0, y1 = sorted((int(y0), int(y1)))
        for y in range(y0, y1):
            for x in range(x0, x1):
                self._set(x, y, c)

    def rect_outline(self, x0, y0, x1, y1, c, t=1):
        self.rect(x0, y0, x1, y0 + t, c)
        self.rect(x0, y1 - t, x1, y1, c)
        self.rect(x0, y0, x0 + t, y1, c)
        self.rect(x1 - t, y0, x1, y1, c)

    def round_panel(self, x0, y0, x1, y1, c, r=12, border=None, bt=2):
        x0, y0, x1, y1 = int(x0), int(y0), int(x1), int(y1)
        self.rect(x0 + r, y0, x1 - r, y1, c)
        self.rect(x0, y0 + r, x1 - r, y1 - r, c)
        self.rect(x1 - r, y0 + r, x1, y1 - r, c)
        for cx, cy in [(x0 + r, y0 + r), (x1 - r, y0 + r),
                       (x0 + r, y1 - r), (x1 - r, y1 - r)]:
            for yy in range(-r, r + 1):
                for xx in range(-r, r + 1):
                    d = math.hypot(xx, yy)
                    if d <= r:
                        px = cx + (xx if cx == x0 + r else xx)
                        py = cy + yy
                        # only draw the outer corner quadrant
                        if cx == x0 + r and xx > 0:
                            continue
                        if cx == x1 - r and xx < 0:
                            continue
                        if cy == y0 + r and yy > 0:
                            continue
                        if cy == y1 - r and yy < 0:
                            continue
                        a = max(0.0, min(1.0, r - d))
                        self._blend(px, py, c, a if a < 1 else 1.0)
                        if a >= 0.5:
                            self._set(px, py, c)
        if border:
            self._round_border(x0, y0, x1, y1, r, border, bt)

    def _round_border(self, x0, y0, x1, y1, r, c, t):
        self.rect(x0 + r, y0, x1 - r, y0 + t, c)
        self.rect(x0 + r, y1 - t, x1 - r, y1, c)
        self.rect(x0, y0 + r, x0 + t, y1 - r, c)
        self.rect(x1 - t, y0 + r, x1, y1 - r, c)
        for cx, cy, xs, ys in [(x0 + r, y0 + r, -1, -1), (x1 - r, y0 + r, 1, -1),
                               (x0 + r, y1 - r, -1, 1), (x1 - r, y1 - r, 1, 1)]:
            for deg in range(0, 91):
                ang = math.radians(deg)
                for tt in range(t):
                    px = int(cx + xs * (r - tt) * math.cos(ang))
                    py = int(cy + ys * (r - tt) * math.sin(ang))
                    self._set(px, py, c)

    def line(self, x0, y0, x1, y1, c, t=1):
        x0, y0, x1, y1 = int(x0), int(y0), int(x1), int(y1)
        dx = abs(x1 - x0)
        dy = abs(y1 - y0)
        sx = 1 if x0 < x1 else -1
        sy = 1 if y0 < y1 else -1
        err = dx - dy
        while True:
            for oy in range(-(t // 2), t - t // 2):
                for ox in range(-(t // 2), t - t // 2):
                    self._set(x0 + ox, y0 + oy, c)
            if x0 == x1 and y0 == y1:
                break
            e2 = 2 * err
            if e2 > -dy:
                err -= dy
                x0 += sx
            if e2 < dx:
                err += dx
                y0 += sy

    def arrow(self, x0, y0, x1, y1, c, t=2, head=9):
        self.line(x0, y0, x1, y1, c, t)
        ang = math.atan2(y1 - y0, x1 - x0)
        for a in (ang + math.radians(150), ang - math.radians(150)):
            hx = x1 + head * math.cos(a)
            hy = y1 + head * math.sin(a)
            self.line(x1, y1, hx, hy, c, t)

    def circle(self, cx, cy, r, c, fill=True, t=2):
        cx, cy, r = int(cx), int(cy), int(r)
        if fill:
            for y in range(-r, r + 1):
                for x in range(-r, r + 1):
                    if x * x + y * y <= r * r:
                        self._set(cx + x, cy + y, c)
        else:
            for deg in range(0, 360):
                ang = math.radians(deg)
                for tt in range(t):
                    self._set(int(cx + (r - tt) * math.cos(ang)),
                              int(cy + (r - tt) * math.sin(ang)), c)

    def text(self, x, y, s, c=(0, 0, 0), scale=2, spacing=1):
        cx = int(x)
        for ch in s:
            glyph = _FONT.get(ch, _FONT.get(ch.upper(), _FONT[' ']))
            for ry, row in enumerate(glyph):
                for rxi, bit in enumerate(row):
                    if bit == '1':
                        self.rect(cx + rxi * scale, int(y) + ry * scale,
                                  cx + rxi * scale + scale,
                                  int(y) + ry * scale + scale, c)
            cx += (5 + spacing) * scale

    def text_w(self, s, scale=2, spacing=1):
        return len(s) * (5 + spacing) * scale - spacing * scale

    def text_center(self, cx, y, s, c=(0, 0, 0), scale=2, spacing=1):
        self.text(cx - self.text_w(s, scale, spacing) / 2, y, s, c, scale, spacing)

    def save(self, path):
        raw = bytearray()
        for y in range(self.h):
            raw.append(0)
            start = y * self.w * 3
            raw.extend(self.px[start:start + self.w * 3])
        compressed = zlib.compress(bytes(raw), 9)

        def chunk(typ, data):
            c = typ + data
            return (struct.pack('>I', len(data)) + c +
                    struct.pack('>I', zlib.crc32(c) & 0xffffffff))

        png = b'\x89PNG\r\n\x1a\n'
        png += chunk(b'IHDR', struct.pack('>IIBBBBB', self.w, self.h, 8, 2, 0, 0, 0))
        png += chunk(b'IDAT', compressed)
        png += chunk(b'IEND', b'')
        with open(path, 'wb') as f:
            f.write(png)
        return path
