class Canvas:
    def __init__(self, w, h, bg=(255, 255, 255)):
        self.w = w
        self.h = h
        self.buf = bytearray()
        r, g, b = bg
        row = bytes((r, g, b)) * w
        for _ in range(h):
            self.buf += row

    def _set(self, x, y, color):
        if 0 <= x < self.w and 0 <= y < self.h:
            i = (y * self.w + x) * 3
            self.buf[i] = color[0]
            self.buf[i + 1] = color[1]
            self.buf[i + 2] = color[2]

    def rect(self, x0, y0, x1, y1, color, fill=True):
        x0, x1 = int(min(x0, x1)), int(max(x0, x1))
        y0, y1 = int(min(y0, y1)), int(max(y0, y1))
        if fill:
            for y in range(y0, y1 + 1):
                for x in range(x0, x1 + 1):
                    self._set(x, y, color)
        else:
            for x in range(x0, x1 + 1):
                self._set(x, y0, color); self._set(x, y1, color)
            for y in range(y0, y1 + 1):
                self._set(x0, y, color); self._set(x1, y, color)

    def hline(self, x0, x1, y, color):
        for x in range(int(min(x0, x1)), int(max(x0, x1)) + 1):
            self._set(x, int(y), color)

    def vline(self, x, y0, y1, color):
        for y in range(int(min(y0, y1)), int(max(y0, y1)) + 1):
            self._set(int(x), y, color)

    def line(self, x0, y0, x1, y1, color, width=1):
        x0, y0, x1, y1 = int(round(x0)), int(round(y0)), int(round(x1)), int(round(y1))
        dx = abs(x1 - x0); dy = -abs(y1 - y0)
        sx = 1 if x0 < x1 else -1
        sy = 1 if y0 < y1 else -1
        err = dx + dy
        while True:
            for wx in range(width):
                for wy in range(width):
                    self._set(x0 + wx - width // 2, y0 + wy - width // 2, color)
            if x0 == x1 and y0 == y1:
                break
            e2 = 2 * err
            if e2 >= dy:
                err += dy; x0 += sx
            if e2 <= dx:
                err += dx; y0 += sy

    def polyline(self, pts, color, width=2):
        for i in range(len(pts) - 1):
            self.line(pts[i][0], pts[i][1], pts[i + 1][0], pts[i + 1][1], color, width)

    def circle(self, cx, cy, r, color, fill=True):
        cx, cy, r = int(cx), int(cy), int(r)
        for y in range(-r, r + 1):
            for x in range(-r, r + 1):
                if x * x + y * y <= r * r:
                    if fill or (x * x + y * y >= (r - 1) * (r - 1)):
                        self._set(cx + x, cy + y, color)

    def text(self, x, y, s, color=(0, 0, 0), scale=1):
        cx = int(x)
        for ch in s:
            glyph = _FONT.get(ch, _FONT['?'])
            for col in range(5):
                bits = glyph[col]
                for row in range(7):
                    if bits & (1 << row):
                        for sxp in range(scale):
                            for syp in range(scale):
                                self._set(cx + col * scale + sxp, int(y) + row * scale + syp, color)
            cx += (5 + 1) * scale

    def text_center(self, cx, y, s, color=(0, 0, 0), scale=1):
        width = len(s) * 6 * scale
        self.text(cx - width // 2, y, s, color, scale)

    def save_png(self, path):
        raw = bytearray()
        for y in range(self.h):
            raw.append(0)  # filter type 0
            start = y * self.w * 3
            raw += self.buf[start:start + self.w * 3]
        compressed = zlib.compress(bytes(raw), 9)

        def chunk(typ, data):
            c = struct.pack('>I', len(data)) + typ + data
            crc = zlib.crc32(typ + data) & 0xffffffff
            return c + struct.pack('>I', crc)

        png = b'\x89PNG\r\n\x1a\n'
        ihdr = struct.pack('>IIBBBBB', self.w, self.h, 8, 2, 0, 0, 0)
        png += chunk(b'IHDR', ihdr)
        png += chunk(b'IDAT', compressed)
        png += chunk(b'IEND', b'')
        with open(path, 'wb') as f:
            f.write(png)
