class Canvas:
    def __init__(self, w, h, bg=(255,255,255)):
        self.w, self.h = w, h
        self.px = bytearray()
        r,g,b = bg
        for _ in range(w*h):
            self.px += bytes((r,g,b))

    def _idx(self, x, y): return (y*self.w + x)*3

    def set(self, x, y, c):
        if 0 <= x < self.w and 0 <= y < self.h:
            i = self._idx(x,y)
            self.px[i], self.px[i+1], self.px[i+2] = c

    def fill_rect(self, x0, y0, x1, y1, c):
        if x1 < x0: x0,x1 = x1,x0
        if y1 < y0: y0,y1 = y1,y0
        for y in range(max(0,y0), min(self.h, y1+1)):
            for x in range(max(0,x0), min(self.w, x1+1)):
                self.set(x,y,c)

    def rect(self, x0, y0, x1, y1, c, t=1):
        for i in range(t):
            self.hline(x0, x1, y0+i, c); self.hline(x0, x1, y1-i, c)
            self.vline(y0, y1, x0+i, c); self.vline(y0, y1, x1-i, c)

    def hline(self, x0, x1, y, c):
        if x1 < x0: x0,x1 = x1,x0
        for x in range(x0, x1+1): self.set(x,y,c)

    def vline(self, y0, y1, x, c):
        if y1 < y0: y0,y1 = y1,y0
        for y in range(y0, y1+1): self.set(x,y,c)

    def line(self, x0, y0, x1, y1, c, t=1):
        dx = abs(x1-x0); dy = -abs(y1-y0)
        sx = 1 if x0<x1 else -1; sy = 1 if y0<y1 else -1
        err = dx+dy
        while True:
            for ox in range(-(t//2), t//2+1):
                for oy in range(-(t//2), t//2+1):
                    self.set(x0+ox, y0+oy, c)
            if x0==x1 and y0==y1: break
            e2 = 2*err
            if e2 >= dy: err += dy; x0 += sx
            if e2 <= dx: err += dx; y0 += sy

    def circle(self, cx, cy, r, c, fill=False):
        for y in range(-r, r+1):
            for x in range(-r, r+1):
                d = x*x + y*y
                if fill:
                    if d <= r*r: self.set(cx+x, cy+y, c)
                else:
                    if abs(d - r*r) <= r: self.set(cx+x, cy+y, c)

    def text(self, x, y, s, c=(0,0,0), scale=2, spacing=1):
        cx = x
        for ch in s:
            g = FONT.get(ch, FONT.get(ch.upper(), FONT[' ']))
            for ry, row in enumerate(g):
                for rx, bit in enumerate(row):
                    if bit == '1':
                        self.fill_rect(cx+rx*scale, y+ry*scale,
                                       cx+rx*scale+scale-1, y+ry*scale+scale-1, c)
            cx += (5+spacing)*scale
        return cx

    def text_w(self, s, scale=2, spacing=1):
        return len(s)*(5+spacing)*scale

    def text_center(self, cx, y, s, c=(0,0,0), scale=2, spacing=1):
        w = self.text_w(s, scale, spacing)
        self.text(cx - w//2, y, s, c, scale, spacing)

    def save(self, path):
        raw = bytearray()
        for y in range(self.h):
            raw.append(0)
            raw += self.px[y*self.w*3:(y+1)*self.w*3]
        comp = zlib.compress(bytes(raw), 9)
        def chunk(t, d):
            c = t + d
            return struct.pack('>I', len(d)) + c + struct.pack('>I', zlib.crc32(c) & 0xffffffff)
        sig = b'\x89PNG\r\n\x1a\n'
        ihdr = chunk(b'IHDR', struct.pack('>IIBBBBB', self.w, self.h, 8, 2, 0, 0, 0))
        idat = chunk(b'IDAT', comp)
        iend = chunk(b'IEND', b'')
        with open(path, 'wb') as f:
            f.write(sig + ihdr + idat + iend)


def lerp_color(c1, c2, t):
    return tuple(int(c1[i] + (c2[i]-c1[i])*t) for i in range(3))
